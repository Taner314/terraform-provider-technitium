package provider

import (
	"context"
	"strings"

	"gitlab.com/stellivix/terraform-provider-technitium/internal/technitium"

	"github.com/hashicorp/terraform-plugin-framework-validators/stringvalidator"
	"github.com/hashicorp/terraform-plugin-framework/path"
	"github.com/hashicorp/terraform-plugin-framework/resource"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/planmodifier"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/stringdefault"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/stringplanmodifier"
	"github.com/hashicorp/terraform-plugin-framework/schema/validator"
	"github.com/hashicorp/terraform-plugin-framework/types"
)

var tsigAlgorithms = []string{
	"hmac-md5.sig-alg.reg.int", "hmac-sha1", "hmac-sha256", "hmac-sha256-128",
	"hmac-sha384", "hmac-sha384-192", "hmac-sha512", "hmac-sha512-256",
}

var (
	_ resource.ResourceWithConfigure   = &tsigKeyResource{}
	_ resource.ResourceWithImportState = &tsigKeyResource{}
)

func NewTsigKeyResource() resource.Resource { return &tsigKeyResource{} }

type tsigKeyResource struct {
	client *technitium.Client
}

type tsigKeyModel struct {
	ID        types.String `tfsdk:"id"`
	Name      types.String `tfsdk:"name"`
	Algorithm types.String `tfsdk:"algorithm"`
	Secret    types.String `tfsdk:"secret"`
}

func (r *tsigKeyResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_tsig_key"
}

func (r *tsigKeyResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	r.client = ConfigureResourceClient(req, resp)
}

func (r *tsigKeyResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		Description: "Manages one TSIG key in the server settings. Keys not managed by Terraform are left alone.",
		Attributes: map[string]schema.Attribute{
			"id": schema.StringAttribute{Computed: true, Description: "Key name.", PlanModifiers: []planmodifier.String{stringplanmodifier.UseStateForUnknown()}},
			"name": schema.StringAttribute{
				Required: true, PlanModifiers: []planmodifier.String{stringplanmodifier.RequiresReplace()},
				Description: "Key name, e.g. `xfr.example.com`.",
			},
			"algorithm": schema.StringAttribute{
				Optional: true, Computed: true, Default: stringdefault.StaticString("hmac-sha256"),
				Description: "Algorithm: `" + strings.Join(tsigAlgorithms, "`, `") + "`.",
				Validators:  []validator.String{stringvalidator.OneOf(tsigAlgorithms...)},
			},
			"secret": schema.StringAttribute{
				Optional: true, Computed: true, Sensitive: true,
				Description:   "Base64 shared secret. Generated by the server when omitted.",
				PlanModifiers: []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
		},
	}
}

func (r *tsigKeyResource) put(ctx context.Context, m *tsigKeyModel) error {
	name := m.Name.ValueString()
	keys, err := r.client.ModifyTsigKeys(ctx, func(keys []technitium.TsigKey) []technitium.TsigKey {
		out := make([]technitium.TsigKey, 0, len(keys)+1)
		for _, k := range keys {
			if !strings.EqualFold(k.KeyName, name) {
				out = append(out, k)
			}
		}
		secret := ""
		if known(m.Secret) {
			secret = m.Secret.ValueString()
		}
		return append(out, technitium.TsigKey{KeyName: name, SharedSecret: secret, AlgorithmName: m.Algorithm.ValueString()})
	})
	if err != nil {
		return err
	}
	for _, k := range keys {
		if strings.EqualFold(k.KeyName, name) {
			m.applyKey(k)
		}
	}
	return nil
}

func (m *tsigKeyModel) applyKey(k technitium.TsigKey) {
	m.ID = types.StringValue(k.KeyName)
	m.Name = types.StringValue(k.KeyName)
	m.Algorithm = types.StringValue(k.AlgorithmName)
	m.Secret = types.StringValue(k.SharedSecret)
}

func (r *tsigKeyResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan tsigKeyModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.put(ctx, &plan); err != nil {
		resp.Diagnostics.AddError("Error creating TSIG key", err.Error())
		return
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, plan)...)
}

func (r *tsigKeyResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state tsigKeyModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	keys, err := r.client.GetTsigKeys(ctx)
	if err != nil {
		resp.Diagnostics.AddError("Error reading TSIG keys", err.Error())
		return
	}
	for _, k := range keys {
		if strings.EqualFold(k.KeyName, state.Name.ValueString()) {
			state.applyKey(k)
			resp.Diagnostics.Append(resp.State.Set(ctx, state)...)
			return
		}
	}
	resp.State.RemoveResource(ctx)
}

func (r *tsigKeyResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan tsigKeyModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.put(ctx, &plan); err != nil {
		resp.Diagnostics.AddError("Error updating TSIG key", err.Error())
		return
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, plan)...)
}

func (r *tsigKeyResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state tsigKeyModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	_, err := r.client.ModifyTsigKeys(ctx, func(keys []technitium.TsigKey) []technitium.TsigKey {
		out := keys[:0]
		for _, k := range keys {
			if !strings.EqualFold(k.KeyName, state.Name.ValueString()) {
				out = append(out, k)
			}
		}
		return out
	})
	if err != nil {
		resp.Diagnostics.AddError("Error deleting TSIG key", err.Error())
	}
}

func (r *tsigKeyResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("name"), req.ID)...)
}
